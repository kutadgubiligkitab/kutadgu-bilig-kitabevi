test("rollback RPC simulation updates only price, writes rollback history, and no-ops safely",()=>{
  const store=Hist.createHistoryStore(
    [{id:"1",price:390,original_price:350},{id:"2",price:200,original_price:200}],
    [{id:11,book_id:"1",old_price:350,new_price:390,change_kind:"price_change",changed_at:"2026-08-01T00:00:00.000Z"},
     {id:12,book_id:"2",old_price:180,new_price:200,change_kind:"price_change",changed_at:"2026-08-01T00:00:00.000Z"},
     {id:13,book_id:"1",old_price:null,new_price:350,change_kind:"price_change",changed_at:"2026-07-01T00:00:00.000Z"}]
  );
  const denied=Hist.simulateRollback(store,{bookId:"1",historyId:11,expectedPrice:390,isAdmin:false,aal:"aal2"});
  assert.ok(String(denied.error&&denied.error.message).includes("Admin permission required"));
  const aal=Hist.simulateRollback(store,{bookId:"1",historyId:11,expectedPrice:390,isAdmin:true,aal:"aal1"});
  assert.ok(String(aal.error&&aal.error.message).includes("AAL2 required"));
  const wrong=Hist.simulateRollback(store,{bookId:"1",historyId:12,expectedPrice:390,isAdmin:true,aal:"aal2"});
  assert.ok(String(wrong.error&&wrong.error.message).includes(Hist.WRONG_BOOK_ERROR));
  const stale=Hist.simulateRollback(store,{bookId:"1",historyId:11,expectedPrice:135,isAdmin:true,aal:"aal2"});
  assert.ok(String(stale.error&&stale.error.message).includes(Hist.STALE_PRICE_ERROR));
  assert.strictEqual(store.books["1"].price,390);
  const nil=Hist.simulateRollback(store,{bookId:"1",historyId:13,expectedPrice:390,isAdmin:true,aal:"aal2"});
  assert.ok(String(nil.error&&nil.error.message).includes(Hist.INVALID_ROLLBACK_ERROR));
  const ok=Hist.simulateRollback(store,{bookId:"1",historyId:11,expectedPrice:390,isAdmin:true,aal:"aal2"});
  assert.strictEqual(ok.error,null);
  assert.strictEqual(ok.historyInserted,true);
  assert.strictEqual(store.books["1"].price,350);
  assert.strictEqual(store.books["1"].original_price,350);
  const newest=Hist.historyForBook(store,"1")[0];
  assert.strictEqual(newest.change_kind,"rollback");
  assert.strictEqual(newest.old_price,390);
  assert.strictEqual(newest.new_price,350);
  const noop=Hist.simulateRollback(store,{bookId:"1",historyId:11,expectedPrice:350,isAdmin:true,aal:"aal2"});
  assert.strictEqual(noop.noop,true);
  assert.strictEqual(noop.historyInserted,undefined);
  const rollbackRows=store.history.filter(row=>row.change_kind==="rollback");
  assert.strictEqual(rollbackRows.length,1);
});

