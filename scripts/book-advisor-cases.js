function scoreList(items, testCase, limit) {
  const rows = (Array.isArray(items) ? items : []).slice(0, limit);
  if (testCase.empty) {
    return { hit: rows.length === 0, incorrect: rows.length };
  }
  const accept = new Set(testCase.accept || []);
  const hit = rows.some((row) => accept.has(row && row.category));
  const incorrect = rows.filter((row) => !accept.has(row && row.category)).length;
  return { hit, incorrect };
}

