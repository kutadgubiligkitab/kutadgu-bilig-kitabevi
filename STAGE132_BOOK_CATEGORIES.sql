-- Stage 132 — admin-managed book categories.
-- MANUAL / REVIEWED APPLY ONLY. Do not run from the application or CI.
-- Additive directory. Seeding does not update existing books or volume groups.
-- A rename changes the display label for the matching source only.
-- A bulk move is one transaction. A retire keeps the slug as a redirect.
-- Data-preserving rollback of the directory objects is
-- STAGE132_BOOK_CATEGORIES_ROLLBACK.sql. That rollback does not reverse
-- label or source updates already written onto books or groups.

BEGIN;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM information_schema.columns
    WHERE table_schema = 'public'
      AND table_name = 'books'
      AND column_name = 'source'
  ) OR NOT EXISTS (
    SELECT 1
    FROM information_schema.columns
    WHERE table_schema = 'public'
      AND table_name = 'books'
      AND column_name = 'category'
  ) OR to_regclass('public.book_volume_groups') IS NULL
    OR to_regclass('public.book_volume_group_members') IS NULL THEN
    RAISE EXCEPTION 'stage132_preflight_failed'
      USING ERRCODE = '55000',
            DETAIL = 'books.category, books.source, and volume-group tables are required';
  END IF;
END;
$$;

CREATE TABLE IF NOT EXISTS public.book_categories (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug text NOT NULL,
  source text NOT NULL,
  label text NOT NULL,
  summary text NOT NULL DEFAULT '',
  icon text NOT NULL DEFAULT '📚',
  sort_order integer NOT NULL,
  is_hidden boolean NOT NULL DEFAULT false,
  retired_at timestamptz,
  redirect_category_id bigint,
  revision bigint NOT NULL DEFAULT 1 CHECK (revision >= 1),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT book_categories_slug_chk CHECK (slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$'),
  CONSTRAINT book_categories_source_chk CHECK (source = slug || '.html'),
  CONSTRAINT book_categories_label_chk CHECK (char_length(btrim(label)) BETWEEN 1 AND 80),
  CONSTRAINT book_categories_summary_chk CHECK (char_length(summary) <= 240),
  CONSTRAINT book_categories_icon_chk CHECK (char_length(icon) BETWEEN 1 AND 16),
  CONSTRAINT book_categories_redirect_chk CHECK (
    (retired_at IS NULL AND redirect_category_id IS NULL)
    OR (retired_at IS NOT NULL AND redirect_category_id IS NOT NULL AND redirect_category_id <> id)
  )
);

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'book_categories_redirect_fkey'
      AND conrelid = 'public.book_categories'::regclass
  ) THEN
    ALTER TABLE public.book_categories
      ADD CONSTRAINT book_categories_redirect_fkey
      FOREIGN KEY (redirect_category_id) REFERENCES public.book_categories(id);
  END IF;
END;
$$;

CREATE UNIQUE INDEX IF NOT EXISTS book_categories_slug_uidx
  ON public.book_categories (slug);
CREATE UNIQUE INDEX IF NOT EXISTS book_categories_source_uidx
  ON public.book_categories (source);
CREATE INDEX IF NOT EXISTS book_categories_order_idx
  ON public.book_categories (sort_order, id);

CREATE TABLE IF NOT EXISTS public.book_category_operations (
  request_id uuid PRIMARY KEY,
  result jsonb NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.book_categories ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.book_category_operations ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.book_categories FROM PUBLIC, anon, authenticated;
REVOKE ALL ON public.book_category_operations FROM PUBLIC, anon, authenticated;

