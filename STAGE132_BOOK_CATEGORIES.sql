CREATE OR REPLACE FUNCTION public.admin_create_book_category(
  p_request_id uuid,
  p_label text,
  p_slug text,
  p_summary text DEFAULT '',
  p_icon text DEFAULT '📚'
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $admin_create_category$
DECLARE
  v_saved jsonb;
  v_label text := btrim(coalesce(p_label, ''));
  v_slug text := lower(btrim(coalesce(p_slug, '')));
  v_summary text := btrim(coalesce(p_summary, ''));
  v_icon text := btrim(coalesce(p_icon, ''));
  v_id bigint;
  v_order integer;
  v_result jsonb;
BEGIN
  IF coalesce(public.is_kutadgu_admin(), false) IS NOT TRUE
     OR (SELECT auth.jwt()->>'aal') IS DISTINCT FROM 'aal2' THEN
    RAISE EXCEPTION 'Admin AAL2 required' USING ERRCODE = '42501';
  END IF;
  IF p_request_id IS NULL THEN
    RAISE EXCEPTION 'request_id_required' USING ERRCODE = '22023';
  END IF;
  SELECT result INTO v_saved
  FROM public.book_category_operations
  WHERE request_id = p_request_id;
  IF FOUND THEN
    RETURN v_saved;
  END IF;
  IF char_length(v_label) < 1 OR char_length(v_label) > 80
     OR v_slug !~ '^[a-z0-9]+(?:-[a-z0-9]+)*$'
     OR v_slug IN (
       'adabiyat', 'books', 'book', 'cart', 'admin', 'author', 'translator',
       'publisher', 'api', 'sitemap', 'order-info', 'privacy', 'returns',
       'delete-account', 'feedback', 'account', 'favorites', 'my-books', 'search'
     ) THEN
    RAISE EXCEPTION 'invalid_category' USING ERRCODE = '22023';
  END IF;
  IF char_length(v_summary) > 240 THEN
    RAISE EXCEPTION 'invalid_category' USING ERRCODE = '22023';
  END IF;
  IF v_icon = '' THEN
    v_icon := '📚';
  END IF;
  IF char_length(v_icon) > 16 THEN
    RAISE EXCEPTION 'invalid_category' USING ERRCODE = '22023';
  END IF;
  IF EXISTS (
    SELECT 1 FROM public.book_categories
    WHERE slug = v_slug OR source = v_slug || '.html'
  ) THEN
    RAISE EXCEPTION 'slug_in_use' USING ERRCODE = '23505';
  END IF;
  SELECT coalesce(max(sort_order), 0) + 10 INTO v_order FROM public.book_categories;
  INSERT INTO public.book_categories (slug, source, label, summary, icon, sort_order)
  VALUES (v_slug, v_slug || '.html', v_label, v_summary, v_icon, v_order)
  RETURNING id INTO v_id;
  v_result := jsonb_build_object(
    'id', v_id,
    'slug', v_slug,
    'source', v_slug || '.html',
    'label', v_label,
    'sort_order', v_order,
    'revision', 1
  );
  INSERT INTO public.book_category_operations (request_id, result)
  VALUES (p_request_id, v_result);
  RETURN v_result;
END;
$admin_create_category$;

CREATE OR REPLACE FUNCTION public.admin_rename_book_category(
  p_request_id uuid,
  p_id bigint,
  p_expected_revision bigint,
  p_label text
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $admin_rename_category$
DECLARE
  v_saved jsonb;
  v_row public.book_categories%ROWTYPE;
  v_label text := btrim(coalesce(p_label, ''));
  v_source text;
  v_books integer := 0;
  v_groups integer := 0;
  v_result jsonb;
BEGIN
  IF coalesce(public.is_kutadgu_admin(), false) IS NOT TRUE
     OR (SELECT auth.jwt()->>'aal') IS DISTINCT FROM 'aal2' THEN
    RAISE EXCEPTION 'Admin AAL2 required' USING ERRCODE = '42501';
  END IF;
  IF p_request_id IS NULL THEN
    RAISE EXCEPTION 'request_id_required' USING ERRCODE = '22023';
  END IF;
  SELECT result INTO v_saved
  FROM public.book_category_operations
  WHERE request_id = p_request_id;
  IF FOUND THEN
    RETURN v_saved;
  END IF;
  IF char_length(v_label) < 1 OR char_length(v_label) > 80 THEN
    RAISE EXCEPTION 'invalid_category' USING ERRCODE = '22023';
  END IF;
  SELECT source INTO v_source
  FROM public.book_categories
  WHERE id = p_id;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'category_not_found' USING ERRCODE = 'P0002';
  END IF;
  PERFORM 1
  FROM public.books
  WHERE source = v_source
  ORDER BY id
  FOR UPDATE;
  PERFORM 1
  FROM public.book_volume_groups
  WHERE source = v_source
  ORDER BY id
  FOR UPDATE;
  SELECT * INTO v_row
  FROM public.book_categories
  WHERE id = p_id
  FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'category_not_found' USING ERRCODE = 'P0002';
  END IF;
  IF v_row.retired_at IS NOT NULL THEN
    RAISE EXCEPTION 'category_retired' USING ERRCODE = '55000';
  END IF;
  IF v_row.revision IS DISTINCT FROM p_expected_revision THEN
    RAISE EXCEPTION 'category_revision_conflict' USING ERRCODE = '40001';
  END IF;
  UPDATE public.book_categories
  SET label = v_label,
      revision = revision + 1,
      updated_at = now()
  WHERE id = v_row.id
  RETURNING * INTO v_row;
  UPDATE public.books
  SET category = v_label
  WHERE source = v_row.source
    AND category IS DISTINCT FROM v_label;
  GET DIAGNOSTICS v_books = ROW_COUNT;
  UPDATE public.book_volume_groups
  SET category = v_label,
      revision = revision + 1,
      updated_at = now()
  WHERE source = v_row.source
    AND category IS DISTINCT FROM v_label;
  GET DIAGNOSTICS v_groups = ROW_COUNT;
  v_result := jsonb_build_object(
    'id', v_row.id,
    'slug', v_row.slug,
    'source', v_row.source,
    'label', v_row.label,
    'revision', v_row.revision,
    'books', v_books,
    'groups', v_groups
  );
  INSERT INTO public.book_category_operations (request_id, result)
  VALUES (p_request_id, v_result);
  RETURN v_result;
END;
$admin_rename_category$;

CREATE OR REPLACE FUNCTION public.admin_move_book_category_order(
  p_request_id uuid,
  p_id bigint,
  p_expected_revision bigint,
  p_direction text
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $admin_order_category$
DECLARE
  v_saved jsonb;
  v_row public.book_categories%ROWTYPE;
  v_other public.book_categories%ROWTYPE;
  v_result jsonb;
BEGIN
  IF coalesce(public.is_kutadgu_admin(), false) IS NOT TRUE
     OR (SELECT auth.jwt()->>'aal') IS DISTINCT FROM 'aal2' THEN
    RAISE EXCEPTION 'Admin AAL2 required' USING ERRCODE = '42501';
  END IF;
  IF p_request_id IS NULL THEN
    RAISE EXCEPTION 'request_id_required' USING ERRCODE = '22023';
  END IF;
  SELECT result INTO v_saved
  FROM public.book_category_operations
  WHERE request_id = p_request_id;
  IF FOUND THEN
    RETURN v_saved;
  END IF;
  IF p_direction NOT IN ('up', 'down') THEN
    RAISE EXCEPTION 'invalid_direction' USING ERRCODE = '22023';
  END IF;
  SELECT * INTO v_row
  FROM public.book_categories
  WHERE id = p_id
  FOR UPDATE;
  IF NOT FOUND OR v_row.retired_at IS NOT NULL THEN
    RAISE EXCEPTION 'category_not_found' USING ERRCODE = 'P0002';
  END IF;
  IF v_row.revision IS DISTINCT FROM p_expected_revision THEN
    RAISE EXCEPTION 'category_revision_conflict' USING ERRCODE = '40001';
  END IF;
  IF p_direction = 'up' THEN
    SELECT * INTO v_other
    FROM public.book_categories
    WHERE retired_at IS NULL
      AND (sort_order < v_row.sort_order OR (sort_order = v_row.sort_order AND id < v_row.id))
    ORDER BY sort_order DESC, id DESC
    LIMIT 1
    FOR UPDATE;
  ELSE
    SELECT * INTO v_other
    FROM public.book_categories
    WHERE retired_at IS NULL
      AND (sort_order > v_row.sort_order OR (sort_order = v_row.sort_order AND id > v_row.id))
    ORDER BY sort_order, id
    LIMIT 1
    FOR UPDATE;
  END IF;
  IF NOT FOUND THEN
    v_result := jsonb_build_object('id', v_row.id, 'sort_order', v_row.sort_order, 'revision', v_row.revision, 'moved', false);
  ELSE
    UPDATE public.book_categories
    SET sort_order = v_other.sort_order, revision = revision + 1, updated_at = now()
    WHERE id = v_row.id;
    UPDATE public.book_categories
    SET sort_order = v_row.sort_order, revision = revision + 1, updated_at = now()
    WHERE id = v_other.id;
    v_result := jsonb_build_object(
      'id', v_row.id,
      'sort_order', v_other.sort_order,
      'revision', v_row.revision + 1,
      'swapped_id', v_other.id,
      'moved', true
    );
  END IF;
  INSERT INTO public.book_category_operations (request_id, result)
  VALUES (p_request_id, v_result);
  RETURN v_result;
END;
$admin_order_category$;

